/**
 * 4·3체스 기물 표기 — 솔로·온라인 뷰가 공유한다. (엔진 코드 K/G/E/C/H는 불변,
 * 게임 id·라우트·전적 키도 'jungle-janggi' 유지 — 표기만 체스로 교체)
 *
 * 디자인 킥: 원작 십이장기는 원류(동물장기)의 "말에 인쇄된 이동 방향" 발명을 지우고
 * 한자 왕·장·상·자로 바꿨다. 본 구현은 세계인이 아는 체스 기물로 번역하되 그 발명을
 * 되살린다 — 타일 가장자리의 점(핍)이 곧 실제 이동 방향이라, 체스와 이동이 다른
 * 기물(나이트·룩)도 헷갈리지 않는다.
 *
 * 이동 대응: 킹(8방)·비숍(대각)·폰(전진)은 체스와 정확히 일치. 나이트는 L자가 아니라
 * 상하좌우 1칸(장), 룩은 대각 뒤를 뺀 6방향 1칸(후) — 서열로 번역한 이름이다.
 * 폰이 적진에 닿아 룩이 되는 것은 체스의 프로모션과 같은 서사.
 *
 * 글리프는 유니코드 체스 기호(텍스트 표현) — currentColor를 따라 기물 잉크색으로 찍힌다.
 */
import type { PieceType } from './engine.ts';

export const PIECE_GLYPH: Record<PieceType, string> = {
  K: '♚', // 킹 — 8방향 1칸. 잡히면 패배, 적진에서 한 턴 버티면 승리
  G: '♞', // 나이트 — 상하좌우 1칸 (체스의 L자와 다름 — 핍 참조)
  E: '♝', // 비숍 — 대각 4방향 1칸
  C: '♟︎', // 폰 — 앞 1칸 (VS15로 이모지化 방지)
  H: '♜', // 룩 — 적진에 닿은 폰의 프로모션, 대각 뒤를 뺀 6방향 1칸 (금빛 테)
};

export const PIECE_NAME: Record<PieceType, string> = {
  K: '킹',
  G: '나이트',
  E: '비숍',
  C: '폰',
  H: '룩',
};

/** 기물별 이동 방향(본인 시점, 위가 전방) — 상대 기물은 타일째 180° 회전되므로 그대로 맞는다 */
const DIRS: Record<PieceType, readonly string[]> = {
  K: ['n', 'ne', 'e', 'se', 's', 'sw', 'w', 'nw'],
  G: ['n', 'e', 's', 'w'],
  E: ['ne', 'se', 'sw', 'nw'],
  C: ['n'],
  H: ['n', 'ne', 'e', 'w', 's', 'nw'], // 금장형: 대각 뒤 2방향 제외
};

/** 타일 가장자리에 이동 방향 핍을 새긴다 */
export function PiecePips({ type }: { type: PieceType }) {
  return (
    <>
      {DIRS[type].map((d) => (
        <i key={d} className={`jj-pip ${d}`} />
      ))}
    </>
  );
}
